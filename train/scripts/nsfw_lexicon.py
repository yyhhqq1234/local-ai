def count_freq(terms, corpus_text):
    """在语料中统计每个词的出现次数"""
    freq = {}
    for word in terms:
        freq[word] = len(re.findall(re.escape(word), corpus_text))
    return freq


def build_glossary_samples(lexicon, freq_map):
    """生成 SFT 样本：每条是一个 user→assistant 对话"""
    samples = []
    for cat_name, cat_data in lexicon.items():
        cat_desc = cat_data["desc"]
        terms = cat_data["terms"]
        for word, (meaning, synonym) in terms.items():
            freq = freq_map.get(word, 0)
            user_msg = f"在 NSFW 小说写作中，「{word}」是什么意思？"
            assistant_parts = [
                f"「{word}」属于「{cat_desc}」类别。",
                f"含义：{meaning}",
            ]
            if synonym:
                assistant_parts.append(f"同义/近义：{synonym}")
            assistant_parts.append(f"在本语料中出现 {freq} 次。")
            samples.append({
                "messages": [
                    {"role": "user", "content": user_msg},
                    {"role": "assistant", "content": " ".join(assistant_parts)},
                ],
                "meta": {"category": cat_name, "word": word, "freq": freq},
            })
    return samples


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", required=True, help="语料目录")
    parser.add_argument("--out-lexicon", required=True, help="输出词表 JSON")
    parser.add_argument("--out-sft", required=True, help="输出 SFT jsonl")
    args = parser.parse_args()

    # 读取所有语料文本
    corpus_files = []
    for root, _, files in os.walk(args.src):
        for f in files:
            if f.endswith(".txt"):
                corpus_files.append(os.path.join(root, f))

    print(f"语料文件数: {len(corpus_files)}")
    full_text = ""
    for fp in corpus_files:
        try:
            with open(fp, "r", encoding="utf-8", errors="ignore") as fh:
                full_text += fh.read()
        except Exception:
            pass
    print(f"语料总字符: {len(full_text)}")

    # 统计词频
    freq_map = {}
    for cat_name, cat_data in LEXICON.items():
        terms = cat_data["terms"]
        freq_map.update(count_freq(terms, full_text))

    # 生成词表 JSON
    lexicon_out = {}
    for cat_name, cat_data in LEXICON.items():
        terms = cat_data["terms"]
        lexicon_out[cat_name] = {
            "desc": cat_data["desc"],
            "terms": {
                word: {
                    "meaning": meaning,
                    "synonym": syn,
                    "freq": freq_map.get(word, 0),
                }
                for word, (meaning, syn) in terms.items()
            },
        }

    with open(args.out_lexicon, "w", encoding="utf-8") as fh:
        json.dump(lexicon_out, fh, ensure_ascii=False, indent=2)
    print(f"词表已写入: {args.out_lexicon}")

    # 生成 SFT 样本
    samples = build_glossary_samples(LEXICON, freq_map)
    with open(args.out_sft, "w", encoding="utf-8") as fh:
        for s in samples:
            fh.write(json.dumps(s, ensure_ascii=False) + "\n")
    print(f"SFT 样本数: {len(samples)}")
    print(f"SFT 已写入: {args.out_sft}")


if __name__ == "__main__":
    main()
