def build():
    rows = []
    # 6 种问法（覆盖口语 / 正式 / 碎片）
    PHRASES = [
        "{q}",
        "请说明：{q}",
        "{q}（讲清楚就行，不用展开太多）",
        "{q} —— 直接说要点。",
        "有个问题想确认：{q}",
        "{q} 这个我一直没搞明白，给讲讲。",
    ]
    for q, a in TOPICS:
        for ph in PHRASES:
            rows.append({"messages": [
                {"role": "user", "content": ph.format(q=q)},
                {"role": "assistant", "content": a}]})

    # 去重 + 每条再复制一份（提权，240 → 480）
    seen, ded = set(), []
    for r in rows:
        k = r["messages"][0]["content"]
        if k in seen:
            continue
        seen.add(k)
        ded.append(r)
    out = ded * 4          # ×4 提权（228 → 456）

    # 硬校验：assistant 不得含任何工具名
    import re
    BAD = re.compile(r"(kitty_[a-z_]+|reverse_[a-z_]+)")
    viol = [r for r in out if BAD.search(r["messages"][-1]["content"])]
    assert not viol, f"有 {len(viol)} 条回答里出现了工具名，违反约束"

    io.open(OUT, "w", encoding="utf-8").write(
        "\n".join(json.dumps(r, ensure_ascii=False) for r in out) + "\n")
    print(f"[OUT] {OUT}")
    print(f"  主题 {len(TOPICS)} × 问法 6 = {len(ded)} 唯一 → 提权后 {len(out)} 条")
    print(f"  校验：assistant 含工具名的条数 = {len(viol)} ✓")
    print("\n=== 样本 ===")
    print("U:", out[0]["messages"][0]["content"])
    print("A:", out[0]["messages"][-1]["content"][:260])


if __name__ == "__main__":
    build()
