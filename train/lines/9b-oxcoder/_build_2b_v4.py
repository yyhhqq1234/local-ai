# ── 问法变体（6 种互不相同，保证每题 6 条唯一 user）────────────────
TMPL = [
    "{q}",
    "请回答：{q}",
    "{q}（简要即可，给要点）",
    "{q} —— 直接说结论，别绕。",
    "想确认一下：{q}",
    "帮我理清楚这件事：{q}",
]


def main():
    if not os.path.exists(SRC):
        raise SystemExit(f"缺输入：{SRC}")

    rows = []
    with open(SRC, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    print(f"[IN ] v3b {len(rows)} 条")

    def emit(pool, src_tag):
        out = []
        for q, a in pool:
            for t in TMPL:
                qq = t.format(q=q)
                out.append({"id": f"v4norm-{src_tag}-{len(out):04d}",
                            "messages": [
                                {"role": "system", "content": SYS_NORMAL},
                                {"role": "user", "content": qq},
                                {"role": "assistant", "content": a}],
                            "meta": {"src": f"v4-normal-{src_tag}", "kind": "normal"}})
        return out

    newA = emit(A, "know")
    newB = emit(B, "tech")
    newC = emit(C, "discuss")
    new = newA + newB + newC
    new_all = new * REPEAT
    random.seed(SEED)
    random.shuffle(new_all)
    print(f"[NEW] know={len(newA)} tech={len(newB)} discuss={len(newC)} "
          f"× {REPEAT} → {len(new_all)}")

    # 去重：旧数据严格去重；normal 桶的重复份**保留**（用作训练端提权）
    seen, merged = set(), []
    for r in rows:
        k = "|".join(m.get("content", "") for m in r["messages"])
        if k in seen:
            continue
        seen.add(k)
        merged.append(r)
    keep = [r for r in new_all
            if "|".join(m.get("content", "") for m in r["messages"]) not in seen]
    merged.extend(keep)

    with open(OUT, "w", encoding="utf-8") as f:
        for r in merged:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    grp = collections.Counter(
        (r.get("id", "").rsplit("#", 1)[-1] if "#" in r.get("id", "")
         else ("normal" if r.get("id", "").startswith("v4norm") else "ctl"))
        for r in merged)
    print(f"[OUT] {OUT}")
    print(f"  合计 {len(merged)} 条 · 分布 {dict(grp)}")

    # token 份额
    def tok(s):
        return int(len(s) / 1.6)
    tot = collections.Counter()
    for r in merged:
        g = (r.get("id", "").rsplit("#", 1)[-1] if "#" in r.get("id", "")
             else ("normal" if r.get("id", "").startswith("v4norm") else "ctl"))
        tot[g] += sum(tok(m.get("content", "")) for m in r["messages"])
    s = sum(tot.values()) or 1
    print("  token 份额：", {k: round(v / s, 4) for k, v in tot.items()})


if __name__ == "__main__":
    main()
