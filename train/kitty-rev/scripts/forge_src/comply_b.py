("堆喷（heap spray）想解决什么",
"""解决「不知道目标地址」——用大量重复对象把可控数据铺满地址空间。

1. 场景：堆地址不可预测（ASLR + 分配器随机化），但你知道「大概率落在一片区域」
2. 做法：分配几百 MB 的同尺寸对象，每个都填「NOP 滑板 + 载荷」，
   这样即使跳转地址不精确，也会落到滑板上滑到载荷
3. 现代限制：64 位地址空间太大，铺不满；分配器有随机化；
   滑板本身可能被检测（大块 NOP 是特征）
4. 替代思路：改「精确地址」而不是「猜地址」—— 用信息泄露拿真实地址更可靠
5. 判据：跳跃地址与滑板覆盖区有交集（统计上）

判据：多次运行，跳转命中的成功率（应该接近 100%，否则铺得不够）
坑：堆喷在现代系统上更多用于「占位/布局」（让某对象落在某地址附近），
   而不是「盲猜代码地址」"""),

