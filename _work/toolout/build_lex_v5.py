# ── 收集所有 assistant 文本（用于频率 + 上下文）──
all_texts = []
with open(os.path.join(base, "nsfw.jsonl"), encoding="utf-8") as f:
    for line in f:
        obj = json.loads(line)
        for msg in obj.get("messages", []):
            if msg.get("role") == "assistant":
                all_texts.append(msg["content"])

print(f"Loaded {len(all_texts)} texts")

def count_term(term):
    """统计 term 在所有文本中的出现次数"""
    c = 0
    for t in all_texts:
        c += t.count(term)
    return c

def find_context(term, max_ctx=2, ctx_len=80):
    """找到 term 出现位置的上下文片段"""
    ctxs = []
    for t in all_texts:
        idx = t.find(term)
        if idx >= 0:
            start = max(0, idx - ctx_len // 2)
            end = min(len(t), idx + len(term) + ctx_len // 2)
            snippet = t[start:end]
            # 去掉换行
            snippet = re.sub(r'\n+', ' ', snippet).strip()
            ctxs.append(snippet)
            if len(ctxs) >= max_ctx:
                break
    return ctxs

