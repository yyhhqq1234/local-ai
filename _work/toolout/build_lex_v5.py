# 填充
def fill_terms(category_key, terms_dict):
    cat = d5[category_key]
    for term, (meaning, synonym, _tip) in terms_dict.items():
        freq = count_term(term)
        ctxs = find_context(term) if freq > 0 else []
        cat["terms"][term] = {
            "meaning": meaning,
            "synonym": synonym,
            "writing_tip": _tip or "",
            "freq": freq,
            "context_examples": ctxs
        }

